"""Builds FreegorGuideRetail/Retail/Data/Professions.lua from the game client
tables published by wago.tools (SkillLineAbility, SkillLine).

Only game facts are kept: for every profession recipe, the skill at which it
turns yellow and grey, and the skill points it gives. The add-on reads names,
reagents and what the character knows from the game itself.

Usage (from the repository root):
    python3 -I tools/build_retail_data.py [build]
"""
import csv
import io
import sys
import urllib.request

BUILD = sys.argv[1] if len(sys.argv) > 1 else "12.1.5.70783"
OUT = "FreegorGuideRetail/Retail/Data/Professions.lua"


def table(name):
    url = "https://wago.tools/db2/%s/csv?build=%s" % (name, BUILD)
    req = urllib.request.Request(url, headers={"User-Agent": "FreegorGuide-data-builder/1.0"})
    with urllib.request.urlopen(req, timeout=300) as r:
        return list(csv.DictReader(io.StringIO(r.read().decode("utf-8"))))


skill_lines = {r["ID"]: r for r in table("SkillLine")}
rows = table("SkillLineAbility")

recipes = []
children = {}
for r in rows:
    child = r["SkillupSkillLineID"]
    low, high, ups = int(r["TrivialSkillLineRankLow"]), int(r["TrivialSkillLineRankHigh"]), int(r["NumSkillUps"])
    if child in ("", "0") or high <= 1 or ups <= 0:
        continue  # not a recipe that gives skill (specialisation perks, etc.)
    sl = skill_lines.get(child)
    if not sl or sl["ParentSkillLineID"] in ("", "0"):
        continue
    recipes.append((int(r["Spell"]), int(child), low, high, ups))
    children[int(child)] = (int(sl["ParentSkillLineID"]), int(sl["ParentTierIndex"] or 0))

recipes.sort()
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("-- Generated by tools/build_retail_data.py from the game client tables of build %s\n" % BUILD)
    f.write("-- (wago.tools: SkillLineAbility, SkillLine). Do not edit by hand.\n")
    f.write("-- Recipes[recipeID] = { expansion skill line, yellow at, grey at, skill points }\n")
    f.write("local _, ns = ...\nns.Retail = ns.Retail or {}\n")
    f.write("ns.Retail.DataBuild = %r\n" % BUILD)
    f.write("ns.Retail.SkillLines = {\n")
    for child, (parent, tier) in sorted(children.items()):
        f.write("  [%d] = { %d, %d },\n" % (child, parent, tier))
    f.write("}\nns.Retail.Recipes = {\n")
    for spell, child, low, high, ups in recipes:
        f.write("  [%d] = { %d, %d, %d, %d },\n" % (spell, child, low, high, ups))
    f.write("}\n")
print("%d recipes, %d expansion skill lines -> %s" % (len(recipes), len(children), OUT))
