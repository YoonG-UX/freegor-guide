"""Builds FreegorGuideRetail/Retail/Data/Travel.lua: the game's own travel
network (portals between continents and zones) from the client tables
WaypointNode, WaypointEdge, WaypointSafeLocs, PlayerCondition and ChrRaces
(via wago.tools). The client uses this network for its own quest navigation
("Take the portal from ... to ...").

Kept per node: continent, world position, kind, instruction (English and
French) and the checkable part of its condition: faction, minimum level,
quests and achievements required. Requirements the add-on cannot check
(modifier trees, phases...) are ignored.

Usage (from the repository root):
    python3 -I tools/build_retail_travel.py [build]
"""
import csv
import io
import sys
import urllib.request

BUILD = sys.argv[1] if len(sys.argv) > 1 else "12.1.5.70783"
OUT = "FreegorGuideRetail/Retail/Data/Travel.lua"


def table(name, locale=None):
    url = "https://wago.tools/db2/%s/csv?build=%s" % (name, BUILD)
    if locale:
        url += "&locale=" + locale
    req = urllib.request.Request(url, headers={"User-Agent": "FreegorGuide-data-builder/1.0"})
    with urllib.request.urlopen(req, timeout=300) as r:
        return list(csv.DictReader(io.StringIO(r.read().decode("utf-8"))))


nodes = {r["ID"]: r for r in table("WaypointNode")}
nodes_fr = {r["ID"]: r["Name_lang"] for r in table("WaypointNode", "frFR")}
edges = table("WaypointEdge")
safe = {r["ID"]: r for r in table("WaypointSafeLocs")}
races = table("ChrRaces")
used = {n["PlayerConditionID"] for n in nodes.values()} | {e["PlayerConditionID"] for e in edges}
conds = {r["ID"]: r for r in table("PlayerCondition") if r["ID"] in used}

# race bit -> faction (ChrRaces.Alliance: 0 Alliance, 1 Horde, other neutral)
race_faction = {}
for r in races:
    bit = int(r["PlayableRaceBit"] or -1)
    if bit >= 0:
        race_faction[bit] = {"0": "A", "1": "H"}.get(r["Alliance"], "N")


def faction_of(c):
    lo, hi = int(c.get("RaceMasks_0") or 0), int(c.get("RaceMasks_1") or 0)
    mask = (lo & 0xFFFFFFFF) | ((hi & 0xFFFFFFFF) << 32)
    if mask == 0 or mask == 0xFFFFFFFFFFFFFFFF:
        return None
    sides = {race_faction.get(b) for b in range(64) if mask >> b & 1 and b in race_faction}
    sides.discard("N")
    return sides.pop() if len(sides) == 1 else None


def nums(c, prefix, n):
    return [int(c[prefix + str(i)]) for i in range(n) if c.get(prefix + str(i)) not in (None, "", "0")]


def cond_lua(cid):
    c = conds.get(cid)
    if not c:
        return None
    parts = []
    f = faction_of(c)
    if f:
        parts.append('f = "%s"' % f)
    if int(c.get("MinLevel") or 0) > 1:
        parts.append("lvl = %d" % int(c["MinLevel"]))
    for key, prefix in (("q", "PrevQuestID_"), ("cq", "CurrQuestID_"), ("ach", "Achievement_")):
        v = nums(c, prefix, 4)
        if v:
            parts.append("%s = { %s }" % (key, ", ".join(map(str, v))))
    return "{ %s }" % ", ".join(parts) if parts else None


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


out = []
out.append("-- Generated by tools/build_retail_travel.py from the game client tables of build %s" % BUILD)
out.append("-- (wago.tools: WaypointNode, WaypointEdge, WaypointSafeLocs, PlayerCondition, ChrRaces). Do not edit by hand.")
out.append("-- Nodes[id] = { continent, worldX, worldY, kind (0 building, 1 departure, 2 arrival), condition, en, fr }")
out.append("-- Edges = { { from, to, condition } }: taking the portal at `from` leads to `to`.")
out.append("local _, ns = ...\nns.Retail = ns.Retail or {}")
cond_ids = set()
out.append("ns.Retail.TravelNodes = {")
for nid in sorted(nodes, key=int):
    n = nodes[nid]
    loc = safe.get(n["SafeLocID"])
    if not loc:
        continue
    cid = n["PlayerConditionID"]
    if cond_lua(cid):
        cond_ids.add(cid)
    out.append("  [%s] = { %s, %.1f, %.1f, %s, %s, %s, %s }," % (
        nid, loc["MapID"], float(loc["Pos_0"]), float(loc["Pos_1"]), n["Type"] or "0",
        cid if cond_lua(cid) else "nil", lua_str(n["Name_lang"]), lua_str(nodes_fr.get(nid, n["Name_lang"]))))
out.append("}")
out.append("ns.Retail.TravelEdges = {")
for e in edges:
    if e["Start"] in nodes and e["End"] in nodes:
        cid = e["PlayerConditionID"]
        if cond_lua(cid):
            cond_ids.add(cid)
        out.append("  { %s, %s, %s }," % (e["Start"], e["End"], cid if cond_lua(cid) else "nil"))
out.append("}")
out.append("ns.Retail.TravelConds = {")
for cid in sorted(cond_ids, key=int):
    out.append("  [%s] = %s," % (cid, cond_lua(cid)))
out.append("}")
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out) + "\n")
print("%d nodes, %d edges, %d conditions -> %s" % (len(nodes), len(edges), len(cond_ids), OUT))
